#!/usr/bin/env python3
"""Generate roboarm/src/boards/wifi_secrets.h from a .env file.

Usage: gen_wifi_secrets.py <env-file> <header-out>
Error messages name keys only, never values.
"""
import os
import re
import sys
import tempfile


def parse_env(text):
    env = {}
    for line in text.split("\n"):
        if line.endswith("\r"):
            line = line[:-1]
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        k, v = line.split("=", 1)
        k, v = k.strip(), v.strip()
        if len(v) >= 2 and v[0] == v[-1] and v[0] in "'\"":
            v = v[1:-1]
        env[k] = v
    return env


def _printable(s):
    return all(0x20 <= ord(c) <= 0x7E for c in s)


def validate(env):
    errs = []
    ssid = env.get("WIFI_SSID")
    pw = env.get("WIFI_PASSWORD")
    key = env.get("ARM_KEY")
    if not ssid:
        errs.append("WIFI_SSID is missing or empty")
    elif len(ssid.encode("utf-8")) > 32:
        errs.append("WIFI_SSID must be 1-32 bytes")
    if not pw:
        errs.append("WIFI_PASSWORD is missing or empty")
    elif not (8 <= len(pw.encode("utf-8")) <= 63) or not _printable(pw):
        errs.append("WIFI_PASSWORD must be 8-63 printable ASCII characters")
    if not key:
        errs.append("ARM_KEY is missing or empty")
    elif not re.fullmatch(r"[A-Za-z0-9_-]{8,64}", key):
        errs.append("ARM_KEY must match [A-Za-z0-9_-]{8,64}")
    return errs


def _c_string(s):
    out = []
    for b in s.encode("utf-8"):
        c = chr(b)
        if c in ('\\', '"', "?"):  # "?" escaped to defeat trigraphs
            out.append("\\" + c)
        elif 0x20 <= b <= 0x7E:
            out.append(c)
        else:
            out.append('\\x%02x""' % b)
    return '"' + "".join(out) + '"'


def render_header(ssid, password, key):
    return (
        "// GENERATED by scripts/gen_wifi_secrets.py from .env - do not edit or commit.\n"
        "#pragma once\n"
        "#define ROBOARM_WIFI_SSID %s\n"
        "#define ROBOARM_WIFI_PASSWORD %s\n"
        "#define ROBOARM_ARM_KEY %s\n"
    ) % (_c_string(ssid), _c_string(password), _c_string(key))


def main(argv):
    if len(argv) != 3:
        print("usage: gen_wifi_secrets.py <env-file> <header-out>", file=sys.stderr)
        return 1
    env_path, out_path = argv[1], argv[2]
    try:
        with open(env_path, encoding="utf-8") as f:
            env = parse_env(f.read())
    except UnicodeDecodeError:
        print("error: %s is not valid UTF-8" % env_path, file=sys.stderr)
        return 1
    except OSError as e:
        print("error: cannot read %s: %s" % (env_path, e.strerror), file=sys.stderr)
        return 1
    errs = validate(env)
    if errs:
        for e in errs:
            print("error: " + e, file=sys.stderr)
        print("Fix %s (see roboarm/src/boards/wifi_secrets.h.example)." % env_path, file=sys.stderr)
        return 1
    content = render_header(env["WIFI_SSID"], env["WIFI_PASSWORD"], env["ARM_KEY"])
    try:
        try:
            with open(out_path, encoding="utf-8") as f:
                same = f.read() == content
        except (OSError, UnicodeDecodeError):
            same = False
        if same:
            os.chmod(out_path, 0o600)
            return 0
        d = os.path.dirname(os.path.abspath(out_path))
        fd, tmp = tempfile.mkstemp(dir=d, prefix=".wifi_secrets.")
        try:
            os.fchmod(fd, 0o600)
            with os.fdopen(fd, "w", encoding="utf-8") as f:
                f.write(content)
            os.replace(tmp, out_path)
        except BaseException:
            try:
                os.unlink(tmp)
            except OSError:
                pass
            raise
    except OSError as e:
        print("error: cannot write %s: %s" % (out_path, e.strerror), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
